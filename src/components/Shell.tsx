export function RecentsMenu({ open, onToggle }: { open: boolean; onToggle: () => void }) {
  return (
    <aside className={'recents' + (open ? '' : ' collapsed')} aria-label="Recent chats">
      <div className="rc-h">
        {open && <span className="t">Recent Chats</span>}
        <span className="btns">
          {open && <button aria-label="Filter"><Icon n="sliders" size={18} /></button>}
          <button onClick={onToggle} aria-label={open ? 'Collapse recent chats' : 'Expand recent chats'}><Icon n="panel" size={18} /></button>
        </span>
      </div>
      {open && (
        <div className="rc-list">
          {RECENTS.map(([g, items]) => (
            <div key={g}>
              <div className="rc-g"><Icon n="chev" size={12} />{g}</div>
              {items.map((i, k) => <div key={g + k} className="rc-i">{i}</div>)}
            </div>
          ))}
        </div>
      )}
    </aside>
  )
}

export function Composer({
  value,
  onChange,
  onSend,
  files,
}: {
  value: string
  onChange: (v: string) => void
  onSend: () => void
  /** number of attached files, shown as a chip (conversation screen) */
  files?: number
}) {
  const ready = !!value.trim()
  const ta = useRef<HTMLTextAreaElement>(null)
  // text row is one line by default and grows as the user types more lines
  useLayoutEffect(() => {
    if (!ta.current) return
    ta.current.style.height = 'auto'
    ta.current.style.height = Math.min(168, ta.current.scrollHeight) + 'px'
  }, [value])

  return (
    <div className="composer">
      <div className="cbox">
        <textarea
          ref={ta}
          rows={1}
          value={value}
          placeholder="Ask anything. The right agent will answer."
          aria-label="Ask anything"
          onChange={(e) => onChange(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === 'Enter' && !e.shiftKey) {
              e.preventDefault()
              if (ready) onSend()
            }
          }}
        />
        <div className="crow">
          <div className="agent"><Sparkle size={15} />Aldar X<Icon n="chev" size={14} /></div>
          <span className="grow" />
          <span className="cnt">{String(value.length).padStart(2, '0')}/20,000</span>
          {!!files && <button className="ib files" aria-label={`${files} attached files`}><Icon n="doc" size={16} /><span>{files}</span></button>}
          <button className="ib" aria-label="Attach"><Icon n="clip" size={17} /></button>
          <button className="ib" aria-label="Dictate"><Icon n="mic" size={17} /></button>
          <button className={'send' + (ready ? ' ready' : '')} onClick={() => ready && onSend()} aria-label="Send"><Icon n="send" size={18} /></button>
        </div>
      </div>
      <p className="disc">Responses are generated by AI — always validate before use.</p>
    </div>
  )
}
